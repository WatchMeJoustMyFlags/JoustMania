"""Generate the mechanical tables of docs/specs from the code (#1280).

    make specs          # rewrite docs/specs/generated/*.md
    make specs-check    # fail if any generated file is out of date (CI)
    make specs-counts   # print the flag, RPC and metric totals (not committed)

Each table is its own small file under docs/specs/generated/, linked from the
hand-written spec. The hand-written parts of a generated table (RPC
descriptions, metric notes) live in sidecars under docs/specs/notes/, keyed by
name and merged in. A generated file is never edited by hand: after a rebase
that conflicts in one, take either side and run `make specs`.

Sources:
    telemetry-metric-catalog.md  Python metric definitions, recording sites and
                                 consumers (tests/contract/telemetry_inventory.py)
                                 + notes/telemetry-metric-catalog.yaml
    grpc-rpcs.md                 proto/*.proto (service and rpc lines)
                                 + notes/grpc-rpcs.yaml
    flag-counts.md               services/flagd/*.json (the flag sets and files)
    flags-ci-diff.md             services/flagd/*.json vs services/flagd/ci/*.json

Committed files carry no count-style aggregates (#2152): a total such as "193
flags" changes with every flag, RPC or metric any PR adds, so two such PRs
always conflicted and the merge queue ejected the later one. The totals are
printed by `make specs-counts` (`--counts`) and CI writes them to the Telemetry
Contract job summary; nothing commits them.

Runs with the standard library plus PyYAML:
    uv run --no-project --with pyyaml python scripts/gen_specs.py [--check | --counts]
"""

from __future__ import annotations

import argparse
import difflib
import json
import re
import sys
from pathlib import Path

import yaml

REPO_ROOT = Path(__file__).resolve().parents[1]
SPECS = REPO_ROOT / "docs" / "specs"
GENERATED = SPECS / "generated"
NOTES = SPECS / "notes"

sys.path.insert(0, str(REPO_ROOT / "tests" / "contract"))
import telemetry_inventory as ti  # noqa: E402

# Replaces every total in a committed file (#2152).
COUNTS_NOTE = (
    "The totals ({what}) are not committed, so two PRs that each add one do not conflict "
    "(#2152): `make specs-counts` prints them, and CI shows them in the Telemetry Contract "
    "job summary.\n"
)

HEADER = (
    "<!-- GENERATED by scripts/gen_specs.py from {sources}. Do not edit: change the "
    "source and run `make specs`. -->\n"
)


class SpecSourceError(Exception):
    """A sidecar is missing an entry or has a stale one."""


def _load_notes(name: str) -> dict[str, str]:
    path = NOTES / f"{name}.yaml"
    if not path.exists():
        return {}
    data = yaml.safe_load(path.read_text()) or {}
    if not isinstance(data, dict):
        raise SpecSourceError(f"{path.relative_to(REPO_ROOT)} must be a mapping")
    return {str(k): " ".join(str(v).split()) for k, v in data.items()}


def _load_label_values(name: str) -> dict[str, dict[str, str]]:
    """metric -> {label: bounded value list}, rendered in the Labels column."""
    path = NOTES / f"{name}.yaml"
    if not path.exists():
        return {}
    data = yaml.safe_load(path.read_text()) or {}
    if not isinstance(data, dict) or not all(
        isinstance(v, dict) for v in data.values()
    ):
        raise SpecSourceError(
            f"{path.relative_to(REPO_ROOT)} must map metric -> {{label: values}}"
        )
    return {
        str(m): {str(k): " ".join(str(v).split()) for k, v in d.items()}
        for m, d in data.items()
    }


def _check_stale(name: str, notes: dict[str, str], known: set[str]) -> None:
    stale = sorted(set(notes) - known)
    if stale:
        raise SpecSourceError(
            f"docs/specs/notes/{name}.yaml has entries for names that no longer exist: "
            f"{stale}; remove or rename them"
        )


def _cell(text: str) -> str:
    return text.replace("|", "\\|")


# --------------------------------------------------------------------------- #
# Telemetry: the Python metric catalog (telemetry.md §6.2)
# --------------------------------------------------------------------------- #
_KIND = {"Counter": "counter", "Gauge": "gauge", "Histogram": "histogram"}


def _definer(module: str) -> str:
    """``services.game_coordinator.metrics`` -> ``game-coordinator``; lib -> ``lib (`lib/x.py`)``."""
    parts = module.split(".")
    if parts[0] == "services":
        return parts[1].replace("_", "-")
    return f"lib (`{'/'.join(parts)}.py`)"


def _emitted(defs: list[ti.PyMetric]) -> str:
    recorded = sorted({_definer(d.module) for d in defs if d.recorded_at})
    silent = sorted({_definer(d.module) for d in defs if not d.recorded_at})
    if not recorded:
        return "**no**: defined, never recorded"
    if not silent:
        return "yes (each service)" if len(defs) > 1 else "yes"
    return f"emitted by {', '.join(recorded)}; defined but never recorded in {', '.join(silent)}"


def _metrics_by_name() -> tuple[list[ti.PyMetric], dict[str, list[ti.PyMetric]]]:
    defs = ti.recorded_python_metric_definitions()
    by_name: dict[str, list[ti.PyMetric]] = {}
    for d in defs:
        by_name.setdefault(d.name, []).append(d)
    return defs, by_name


def metric_counts() -> list[str]:
    """The catalog's totals (#2152: printed by --counts, never committed)."""
    defs, by_name = _metrics_by_name()
    consumers = ti.python_metric_consumers(set(by_name))
    never_recorded = sum(not any(d.recorded_at for d in ds) for ds in by_name.values())
    no_consumer = sum(not kinds for kinds in consumers.values())
    multi = sorted(n for n, ds in by_name.items() if len({d.module for d in ds}) > 1)
    return [
        f"- **{len(by_name)} unique Python metric names** ({len(defs)} definitions; "
        f"{len(multi)} names are defined in more than one module).",
        f"- {no_consumer} of the {len(by_name)} names have no consumer (no Grafana or SPA query, "
        "agent ingest constant, or `tools/` / `scripts/` source names them).",
        f"- {never_recorded} names are defined but never recorded by any service.",
    ]


def telemetry_metric_catalog() -> str:
    name = "telemetry-metric-catalog"
    _, by_name = _metrics_by_name()
    consumers = ti.python_metric_consumers(set(by_name))
    notes = _load_notes(name)
    _check_stale(name, notes, set(by_name))
    label_values = _load_label_values(f"{name}-labels")
    _check_stale(f"{name}-labels", label_values, set(by_name))

    out = [
        HEADER.format(
            sources="the Python metric definitions, their recording sites and consumer scans "
            "(tests/contract/telemetry_inventory.py) and docs/specs/notes/telemetry-metric-catalog.yaml"
        ),
        "# Python metric catalog (generated)\n",
        "Part of [telemetry.md §6.2](../telemetry.md#62-python-metric-catalog), which defines the "
        "columns.\n",
        COUNTS_NOTE.format(
            what="the number of names, of names without a consumer and of "
            "names never recorded"
        ),
        "| Metric | Type | Labels | Defined in | Emitted | Consumers | Notes |",
        "|---|---|---|---|---|---|---|",
    ]
    for metric in sorted(by_name):
        ds = by_name[metric]
        labels = tuple(dict.fromkeys(label for d in ds for label in d.labels))
        definers = sorted({_definer(d.module) for d in ds})
        for label in label_values.get(metric, {}):
            if label not in labels:
                raise SpecSourceError(
                    f"docs/specs/notes/{name}-labels.yaml: {metric} has no label {label!r}"
                )
        label_cell = (
            ", ".join(
                f"`{label}`"
                + (
                    f" ({label_values[metric][label]})"
                    if label in label_values.get(metric, {})
                    else ""
                )
                for label in labels
            )
            or "(none)"
        )
        out.append(
            "| "
            + " | ".join(
                [
                    f"`{metric}`",
                    _KIND[ds[0].kind],
                    _cell(label_cell),
                    ", ".join(definers),
                    _emitted(ds),
                    ", ".join(sorted(consumers[metric])) or "(none)",
                    _cell(notes.get(metric, "")),
                ]
            )
            + " |"
        )
    return "\n".join(out) + "\n"


# --------------------------------------------------------------------------- #
# gRPC: one table per proto service (services.md §3)
# --------------------------------------------------------------------------- #
_PACKAGE_RE = re.compile(r"^\s*package\s+([\w.]+)\s*;")
_SERVICE_RE = re.compile(r"^\s*service\s+(\w+)\s*\{")
_RPC_RE = re.compile(
    r"^\s*rpc\s+(\w+)\s*\(\s*(stream\s+)?([\w.]+)\s*\)\s*returns\s*\(\s*(stream\s+)?([\w.]+)\s*\)"
)
_RPC_KIND = {
    (False, False): "unary",
    (False, True): "server stream",
    (True, False): "client stream",
    (True, True): "bidi stream",
}


def proto_rpcs() -> list[tuple[str, str, list[tuple[str, str, str, str]]]]:
    """[(full service name, proto path, [(rpc, kind, request, response)])]."""
    services = []
    for path in sorted((REPO_ROOT / "proto").glob("*.proto")):
        rel = path.relative_to(REPO_ROOT).as_posix()
        package = ""
        current: list | None = None
        for line in path.read_text().splitlines():
            if m := _PACKAGE_RE.match(line):
                package = m.group(1)
            elif m := _SERVICE_RE.match(line):
                current = []
                services.append((f"{package}.{m.group(1)}", rel, current))
            elif (m := _RPC_RE.match(line)) and current is not None:
                kind = _RPC_KIND[(bool(m.group(2)), bool(m.group(4)))]
                current.append((m.group(1), kind, m.group(3), m.group(5)))
            elif line.strip().startswith("}") and not line.startswith(" "):
                current = None
    return services


def grpc_rpcs() -> str:
    name = "grpc-rpcs"
    services = proto_rpcs()
    notes = _load_notes(name)
    keys = {f"{svc}/{rpc[0]}" for svc, _, rpcs in services for rpc in rpcs}
    _check_stale(name, notes, keys)
    missing = sorted(keys - set(notes))
    if missing:
        raise SpecSourceError(
            f"docs/specs/notes/{name}.yaml has no description for {missing}; add one per RPC"
        )
    out = [
        HEADER.format(sources="proto/*.proto and docs/specs/notes/grpc-rpcs.yaml"),
        "# gRPC services (generated)\n",
        "Part of [services.md §3](../services.md#3-grpc-services).\n",
        COUNTS_NOTE.format(what="RPCs in all and per service"),
    ]
    for svc, rel, rpcs in services:
        out += [
            f"## `{svc}` (`{rel}`)\n",
            "| RPC | Kind | Request → Response | Description |",
            "|---|---|---|---|",
        ]
        for rpc, kind, req, resp in rpcs:
            out.append(
                f"| `{rpc}` | {kind} | `{req}` → `{resp}` | "
                f"{_cell(notes[f'{svc}/{rpc}'])} |"
            )
        out.append("")
    return "\n".join(out)


def rpc_counts() -> list[str]:
    services = proto_rpcs()
    total = sum(len(rpcs) for _, _, rpcs in services)
    return [f"- **{total} RPCs in {len(services)} services.**"] + [
        f"  - `{svc}`: {len(rpcs)}" for svc, _, rpcs in services
    ]


# --------------------------------------------------------------------------- #
# Flags: the flag sets (counts via --counts) and the ci/ baseline differences (flags.md)
# --------------------------------------------------------------------------- #
FLAGD = REPO_ROOT / "services" / "flagd"
# The order flags.md documents the sets in; a new file is appended by name.
FLAG_SET_ORDER = (
    "agent",
    "game",
    "interventions",
    "controller",
    "rollout",
    "operator",
    "system",
    "user",
    "observability",
)


def _flag_files(base: Path) -> dict[str, dict]:
    return {
        p.stem: json.loads(p.read_text())["flags"] for p in sorted(base.glob("*.json"))
    }


def _ordered_sets(sets: dict[str, dict]) -> list[str]:
    known = [s for s in FLAG_SET_ORDER if s in sets]
    return known + sorted(set(sets) - set(known))


def flag_counts() -> str:
    """The flag sets and their files. The file keeps its name (flags.md links it); the
    per-set counts moved to --counts (#2152), so adding a flag no longer changes it."""
    order = _ordered_sets(_flag_files(FLAGD))
    out = [
        HEADER.format(sources="services/flagd/*.json"),
        "# Flag sets (generated)\n",
        "Part of [flags.md](../flags.md). One flagd file per flag set; the `ci/` copies "
        "(flags.md §12) are not listed.\n",
        COUNTS_NOTE.format(what="flags in all and per set"),
        "| Flag set | File |",
        "|---|---|",
    ]
    for s in order:
        out.append(
            f"| `{s}` | [`services/flagd/{s}.json`](../../../services/flagd/{s}.json) |"
        )
    return "\n".join(out) + "\n"


def flag_set_counts() -> list[str]:
    sets = _flag_files(FLAGD)
    order = _ordered_sets(sets)
    total = sum(len(sets[s]) for s in order)
    return [
        f"- **{total} flags in {len(order)} flag sets** (`ci/` copies not counted)."
    ] + [f"  - `{s}`: {len(sets[s])}" for s in order]


def render_counts() -> str:
    """Markdown for --counts / the CI job summary; never written under docs/."""
    return (
        "\n".join(
            [
                "## Spec counts (generated, not committed, #2152)\n",
                "### Flags\n",
                *flag_set_counts(),
                "",
                "### gRPC\n",
                *rpc_counts(),
                "",
                "### Python metrics\n",
                *metric_counts(),
            ]
        )
        + "\n"
    )


def _variant(flag: dict, variant: str) -> str:
    value = flag["variants"].get(variant)
    shown = "(object)" if isinstance(value, (dict, list)) else json.dumps(value)
    return f"`{variant}` = {_cell(shown)}"


def flags_ci_diff() -> str:
    base = _flag_files(FLAGD)
    ci = _flag_files(FLAGD / "ci")
    defaults, added, removed, only = [], [], [], []
    for s in sorted(set(base) | set(ci)):
        b, c = base.get(s, {}), ci.get(s, {})
        file = f"{s}.json"
        for key in sorted(set(b) ^ set(c)):
            only.append(
                f"| {file} | `{key}` | {'base only' if key in b else '`ci/` only'} |"
            )
        for key in sorted(set(b) & set(c)):
            fb, fc = b[key], c[key]
            if fb.get("defaultVariant") != fc.get("defaultVariant") or fb[
                "variants"
            ].get(fb.get("defaultVariant")) != fc["variants"].get(
                fc.get("defaultVariant")
            ):
                defaults.append(
                    f"| {file} | `{key}` | {_variant(fb, fb['defaultVariant'])} | "
                    f"{_variant(fc, fc['defaultVariant'])} |"
                )
            for v in sorted(set(fc["variants"]) - set(fb["variants"])):
                added.append(f"| {file} | `{key}` | {_variant(fc, v)} |")
            for v in sorted(set(fb["variants"]) - set(fc["variants"])):
                removed.append(f"| {file} | `{key}` | {_variant(fb, v)} |")
    out = [
        HEADER.format(sources="services/flagd/*.json and services/flagd/ci/*.json"),
        "# `ci/` flag differences (generated)\n",
        "Part of [flags.md §12](../flags.md#12-ci-differences). A table with no rows means no "
        "difference of that kind; there is no placeholder row, so the first two PRs that each "
        "add a row do not both replace the same line (#2152).\n",
        "## Defaults that differ\n",
        "| File | Key | Base default | `ci/` default |",
        "|---|---|---|---|",
        *defaults,
        "",
        "## Variants only in `ci/`\n",
        "| File | Key | Variant |",
        "|---|---|---|",
        *added,
        "",
        "## Variants only in the base file\n",
        "| File | Key | Variant |",
        "|---|---|---|",
        *removed,
        "",
        "## Keys in only one of the two\n",
        "| File | Key | Where |",
        "|---|---|---|",
        *only,
    ]
    return "\n".join(out) + "\n"


# --------------------------------------------------------------------------- #
GENERATORS = {
    "telemetry-metric-catalog.md": telemetry_metric_catalog,
    "grpc-rpcs.md": grpc_rpcs,
    "flag-counts.md": flag_counts,
    "flags-ci-diff.md": flags_ci_diff,
}


def render_all() -> dict[Path, str]:
    return {GENERATED / name: gen() for name, gen in GENERATORS.items()}


def stale_files(rendered: dict[Path, str]) -> list[tuple[Path, str]]:
    """(path, unified diff) for each generated file that differs from what is on disk."""
    out = []
    for path, text in rendered.items():
        current = path.read_text() if path.exists() else ""
        if current != text:
            rel = path.relative_to(REPO_ROOT).as_posix()
            diff = "".join(
                difflib.unified_diff(
                    current.splitlines(keepends=True),
                    text.splitlines(keepends=True),
                    f"a/{rel} (committed)",
                    f"b/{rel} (from the code)",
                    n=0,
                )
            )
            out.append((path, diff))
    # A generated file without a generator is stale too.
    for path in sorted(GENERATED.glob("*.md")):
        if path not in rendered:
            out.append(
                (path, f"{path.relative_to(REPO_ROOT)}: no generator produces it\n")
            )
    return out


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument(
        "--check", action="store_true", help="fail if a generated file is stale"
    )
    mode.add_argument(
        "--counts",
        action="store_true",
        help="print the flag, RPC and metric totals (not committed, #2152)",
    )
    args = parser.parse_args(argv)
    if args.counts:
        try:
            print(render_counts(), end="")
        except SpecSourceError as err:
            print(f"gen_specs: {err}", file=sys.stderr)
            return 1
        return 0
    try:
        rendered = render_all()
    except SpecSourceError as err:
        print(f"gen_specs: {err}", file=sys.stderr)
        return 1
    if args.check:
        stale = stale_files(rendered)
        if not stale:
            print(f"docs/specs/generated: {len(rendered)} files up to date.")
            return 0
        for _, diff in stale:
            lines = diff.splitlines()
            print(
                "\n".join(
                    lines[:40]
                    + (
                        [f"... ({len(lines) - 40} more lines)"]
                        if len(lines) > 40
                        else []
                    )
                )
            )
        names = ", ".join(p.relative_to(REPO_ROOT).as_posix() for p, _ in stale)
        print(
            f"\n::error title=Generated specs out of date::{names} out of date. "
            "Run `make specs` and commit the result (after a rebase conflict in a "
            "generated file, take either side and run `make specs`).",
            file=sys.stderr,
        )
        return 1
    GENERATED.mkdir(parents=True, exist_ok=True)
    for path, text in rendered.items():
        if not path.exists() or path.read_text() != text:
            path.write_text(text)
            print(f"wrote {path.relative_to(REPO_ROOT)}")
    for path, _ in stale_files(rendered):
        path.unlink()
        print(f"removed {path.relative_to(REPO_ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
